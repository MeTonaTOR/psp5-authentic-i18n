"""Makes src/libicon_data.inc: the picture of the Library card for every height the card can have, ready-made.

    python3 tools/gen_library_icons.py

Calculating the picture takes a few milliseconds on a PC, which is far too long for a PSP while the card grows (a new height
every frame), so the heights the card goes through are stored and only the others are calculated (icons.c, icon_library_image).
The images come from the same code (icon_render, ICON_LIBRARY), so they are exactly what it would calculate; the host test
host-tests/icons/librarytest.py checks that the file is up to date. Run this again whenever the picture or the card's sizes change.

Each image is stored as pairs (coverage, run length) in the order of the pixels, row by row. Needs gcc.
"""
import ctypes as C
import os
import re
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "src")
# the card is 33 px high small and 62 px high big, the picture two thirds of that (gfx_library_icon); one more at each end
FIRST, LAST = 21, 42


def main():
    with open(os.path.join(SRC, "icons.h")) as f:
        names = re.findall(r"\b(ICON_[A-Z_]+)\b\s*[,/\n]", f.read().split("enum {", 1)[1].split("};", 1)[0])
    kind = names.index("ICON_LIBRARY")
    with tempfile.TemporaryDirectory() as tmp:
        lib = os.path.join(tmp, "libicons.so")
        subprocess.check_call(["gcc", "-O2", "-shared", "-fPIC", "-DLIB_NO_BAKED", "-I" + SRC, "-o", lib, os.path.join(SRC, "icons.c"), "-lm"])
        L = C.CDLL(lib)
    L.icon_library_width.argtypes = [C.c_int]
    L.icon_render.argtypes = [C.c_int] + [C.c_float] * 5 + [C.c_int, C.c_int, C.c_void_p]
    data, offsets = [], []
    for h in range(FIRST, LAST + 1):
        w = L.icon_library_width(h)
        out = (C.c_ubyte * (w * h))()
        L.icon_render(kind, w, h, 0, w / 2.0, h / 2.0, w, h, out)
        offsets.append(len(data))
        px, i = bytes(out), 0
        while i < len(px):
            j = i
            while j < len(px) and px[j] == px[i] and j - i < 255:
                j += 1
            data += [px[i], j - i]
            i = j
    offsets.append(len(data))
    lines = ["/* Generated by tools/gen_library_icons.py - do not edit. The picture of the Library card for the heights %d .. %d," % (FIRST, LAST),
             " * run length coded: pairs (coverage, number of pixels), row after row (icons.c, icon_library_image). */",
             "#define LIB_BAKED_FIRST %d" % FIRST, "#define LIB_BAKED_LAST %d" % LAST,
             "static const unsigned short lib_baked_start[%d] = {" % len(offsets)]
    lines += ["    " + ", ".join(str(o) for o in offsets[i:i + 12]) + "," for i in range(0, len(offsets), 12)]
    lines += ["};", "static const unsigned char lib_baked[%d] = {" % len(data)]
    lines += ["    " + ",".join(str(b) for b in data[i:i + 24]) + "," for i in range(0, len(data), 24)]
    lines += ["};", ""]
    with open(os.path.join(SRC, "libicon_data.inc"), "w", newline="\n") as f:
        f.write("\n".join(lines))
    print("src/libicon_data.inc: %d images, %d bytes of data" % (LAST - FIRST + 1, len(data)))


if __name__ == "__main__":
    sys.exit(main())
